import assert from 'node:assert/strict';
import {sourceFramesToSeconds, castingBoundarySourceFrame, previewCycleDps, compareDpsRows} from './timing-model.mjs';
assert.equal(sourceFramesToSeconds(30), 1);
assert.equal(sourceFramesToSeconds(114), 3.8);
assert.equal(castingBoundarySourceFrame([17,22], 10), 22);
assert.equal(castingBoundarySourceFrame([17,22], 40), 19.5);
assert.equal(castingBoundarySourceFrame([17,22], 70), 17);
assert.equal(castingBoundarySourceFrame([17,22], 0), 22);
assert.equal(castingBoundarySourceFrame([17,22], 99), 17);
assert.equal(castingBoundarySourceFrame([17,22], 11), 22);
assert.throws(() => castingBoundarySourceFrame([22,17], 40));
assert.throws(() => sourceFramesToSeconds(NaN));
const cycle = {cycleSeconds: 2, hits:[{id:'hit1',timeSeconds:0.1,damage:100},{id:'hit2',timeSeconds:1,damage:200}]};
assert.equal(previewCycleDps(cycle).dps, 150);
assert.equal(previewCycleDps(cycle).rankingEligible, false);
assert.throws(() => previewCycleDps({...cycle, cycleSeconds:0}));
assert.throws(() => previewCycleDps({...cycle, hits:[cycle.hits[0],cycle.hits[0]]}));
assert.throws(() => previewCycleDps({...cycle, hits:[{id:'x',timeSeconds:2,damage:1}]}));
const rows=[{id:'z',dps:null},{id:'a',dps:0},{id:'c',dps:20},{id:'b',dps:20},{id:'n',dps:NaN}];
assert.deepEqual([...rows].sort(compareDpsRows).map(x=>x.id), ['b','c','a','n','z']);
assert.deepEqual([...rows].sort((a,b)=>compareDpsRows(a,b,'asc')).map(x=>x.id), ['a','b','c','n','z']);
console.log('Timing model: frame units, vDex, cycle math, duplicate hits, null-last stable sort passed');
